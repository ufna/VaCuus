#!/usr/bin/env python3
"""Tools/gen_sbix_fixture.py -- writes Source/VaCuus/Private/Tests/VaCuusSbixFixture.h, the font
VaCuus.Font.Subpixel.SbixAdvance loads from memory.

    python3 -m venv /tmp/venv && /tmp/venv/bin/pip install fonttools==4.55.3
    /tmp/venv/bin/python Tools/gen_sbix_fixture.py

WHAT THE FONT IS, and why each part is there. One glyph, 'A', advance 600 of 1000 units, with BOTH
a TrueType outline (glyf) and a 32 ppem colour bitmap (sbix). FreeType treats an sbix face that
also has outlines as bitmap-only: it sets FT_FACE_FLAG_SBIX and not FT_FACE_FLAG_SCALABLE
(src/sfnt/sfobjs.c:1103-1110, FreeType 2.14.1). Its glyph loader still stores the hmtx advance in
linearHoriAdvance (src/truetype/ttgload.c:2412), but FT_Load_Glyph converts that field to 16.16
pixels only for a scalable face (src/base/ftobjs.c:1100-1102), so here it stays in font units --
the case RmlUi patch #15's advance must not read as pixels. Apple's emoji fonts are built this way.

THE STRIKE MEASURES EXACTLY ITS PPEM because hhea ascent - descent + line gap = 800 + 200 + 0 = units per
em: FreeType sizes an sbix strike from those (src/sfnt/ttsbit.c:428-435), and RmlUi picks and scales
strikes by that size, so the test's 32 px request takes the 32 ppem strike unscaled. Change the
vertical metrics and the test's expected width moves with them.

The output is deterministic: fixed head timestamps, no recalculation on save, and a PNG written
by hand with fixed zlib settings. The header records the bytes' SHA-256.
"""
import hashlib
import io
import pathlib
import struct
import zlib

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import newTable
from fontTools.ttLib.tables.sbixGlyph import Glyph as SbixGlyph
from fontTools.ttLib.tables.sbixStrike import Strike

UNITS_PER_EM = 1000
ADVANCE = 600
PPEM = 32
FAMILY = "VaCuusSbixFixture"
OUT = pathlib.Path(__file__).resolve().parent.parent / "Source/VaCuus/Private/Tests/VaCuusSbixFixture.h"


def png_rgba(width, height, rgba):
    """A width x height PNG of one opaque colour, with nothing in it that varies between runs."""
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    rows = b"".join(b"\x00" + bytes(rgba) * width for _ in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def build():
    fb = FontBuilder(UNITS_PER_EM, isTTF=True)
    fb.setupGlyphOrder([".notdef", "A"])
    fb.setupCharacterMap({ord("A"): "A"})

    pen = TTGlyphPen(None)
    pen.moveTo((50, 0))
    pen.lineTo((50, 700))
    pen.lineTo((550, 700))
    pen.lineTo((550, 0))
    pen.closePath()
    fb.setupGlyf({".notdef": TTGlyphPen(None).glyph(), "A": pen.glyph()})

    fb.setupHorizontalMetrics({".notdef": (ADVANCE, 0), "A": (ADVANCE, 50)})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
    fb.setupPost()
    fb.setupHead(unitsPerEm=UNITS_PER_EM, created=0, modified=0)

    strike = Strike(ppem=PPEM, resolution=72)
    strike.glyphs["A"] = SbixGlyph(glyphName="A", graphicType="png ", imageData=png_rgba(PPEM, PPEM, (255, 255, 255, 255)))
    sbix = newTable("sbix")
    sbix.version = 1
    sbix.flags = 1
    sbix.strikes = {PPEM: strike}
    fb.font["sbix"] = sbix

    fb.font.recalcTimestamp = False
    out = io.BytesIO()
    fb.save(out)
    return out.getvalue()


def main():
    data = build()
    lines = ["\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    OUT.write_text(
        "// Copyright 2026 Vladimir Alyamkin. All Rights Reserved.\n\n"
        "// GENERATED by Tools/gen_sbix_fixture.py -- edit the script, not this file. The script says what the font is\n"
        f"// and why. {len(data)} bytes, SHA-256 {hashlib.sha256(data).hexdigest()}.\n\n"
        "#pragma once\n\n"
        "#include \"CoreTypes.h\"\n\n"
        "namespace VaCuusSbixFixture\n{\n"
        f"/** Family \"{FAMILY}\": 'A' with a glyf outline and a {PPEM} ppem sbix bitmap, advance {ADVANCE} of {UNITS_PER_EM}. */\n"
        "static const uint8 GBytes[] = {\n" + "\n".join(lines) + "\n};\n"
        "}	 // namespace VaCuusSbixFixture\n")
    print(f"{OUT}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    main()
