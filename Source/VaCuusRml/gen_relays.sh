#!/usr/bin/env bash
# Regenerates Private/Gen/relay_*.cpp — one relay TU per vendored RmlUi Core .cpp.
# UBT only compiles sources inside the module directory, so each vendored .cpp
# gets a relay TU that #includes it. Re-run only when the vendored SHA changes,
# then commit the result.
# Requires GNU coreutils (uses `realpath --relative-to`).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"; RML="$ROOT/../ThirdParty/RmlUi/Source"
[ -d "$RML/Core" ] || { echo "gen_relays.sh: $RML/Core not found" >&2; exit 1; }
git -C "$ROOT/../.." status --porcelain -- Source/ThirdParty/RmlUi/Source/Core | grep -q . && echo 'warning: dirty vendor tree' >&2 || true
OUT="$ROOT/Private/Gen"; rm -rf "$OUT"; mkdir -p "$OUT"
find "$RML/Core" "$RML/SVG" "$RML/Lottie" -name '*.cpp' | sort | while read -r f; do
  rel="$(realpath --relative-to="$OUT" "$f")"
  base="${f#"$RML"/}"; base="${base%.cpp}"; name="$(echo "$base" | tr '/' '_')"
  if [ -e "$OUT/relay_${name}.cpp" ]; then
    echo "collision: $name" >&2
    exit 1
  fi
  {
    printf '// Auto-generated by gen_relays.sh — do not edit.\n'
    printf '#include "%s"\n' "$rel"
  } > "$OUT/relay_${name}.cpp"
done
n=$(find "$OUT" -maxdepth 1 -name 'relay_*.cpp' | wc -l); [ "$n" -gt 0 ] || { echo "gen_relays.sh: generated 0 relay TUs" >&2; exit 1; }
echo "generated $(ls "$OUT" | wc -l) relay TUs"

# Dependencies are private to this module, but remain separate upstream TUs.
VECTOR_OUT="$ROOT/Private/VectorGen"
mkdir -p "$VECTOR_OUT"
rm -f "$VECTOR_OUT"/*.cpp "$VECTOR_OUT"/*.c
for spec in 'lunasvg/source:cpp:lunasvg' 'lunasvg/plutovg/source:c:plutovg' 'rlottie/src:cpp:rlottie'; do
  IFS=: read -r sub ext label <<< "$spec"
  base="$ROOT/../ThirdParty/$sub"
  find "$base" -name "*.$ext" | sort | while read -r f; do
    name="${f#"$base"/}"; name="${name%.*}"; name="${name//\//_}"
    rel="$(realpath --relative-to="$VECTOR_OUT" "$f")"
    {
      printf '// Generated by gen_relays.sh; preserves an upstream translation unit.\n'
      printf '#if defined(__clang__)\n'
      for warning in deprecated-declarations unused-function shadow undef implicit-fallthrough deprecated-copy deprecated-copy-with-user-provided-copy; do
        printf '#pragma clang diagnostic ignored "-W%s"\n' "$warning"
      done
      printf '#endif\n'
      printf '#if defined(_MSC_VER) && !defined(__clang__)\n#pragma warning(push, 0)\n#endif\n'
      printf '#include "%s"\n' "$rel"
      printf '#if defined(_MSC_VER) && !defined(__clang__)\n#pragma warning(pop)\n#endif\n'
    } > "$VECTOR_OUT/${label}_$name.$ext"
  done
done
